// Lightbox ochish/yopish va navigatsiya
let currentLightboxIndex = 0;
let galleryImagesList = [];

window.openLightbox = function(url) {
    const modal = document.getElementById('lightbox-modal');
    const img = document.getElementById('lightbox-img');
    if (!modal || !img) return;
    
    // Barcha galereya rasmlarini yig'ish
    const images = Array.from(document.querySelectorAll('.gallery-grid img'));
    galleryImagesList = images.map(i => i.src);
    
    currentLightboxIndex = galleryImagesList.indexOf(url);
    if(currentLightboxIndex === -1) currentLightboxIndex = 0;

    img.src = url;
    modal.classList.add('active');
};

window.closeLightbox = function() {
    const modal = document.getElementById('lightbox-modal');
    if (modal) modal.classList.remove('active');
};

window.prevLightboxImage = function() {
    if(galleryImagesList.length === 0) return;
    currentLightboxIndex = (currentLightboxIndex - 1 + galleryImagesList.length) % galleryImagesList.length;
    document.getElementById('lightbox-img').src = galleryImagesList[currentLightboxIndex];
};

window.nextLightboxImage = function() {
    if(galleryImagesList.length === 0) return;
    currentLightboxIndex = (currentLightboxIndex + 1) % galleryImagesList.length;
    document.getElementById('lightbox-img').src = galleryImagesList[currentLightboxIndex];
};

// Touch swipe for Lightbox
let touchstartX = 0;
let touchendX = 0;
let touchstartY = 0;
let touchendY = 0;
    
function handleGesture() {
    // Gorizontal va vertikal siljishni hisoblash
    const deltaX = touchendX - touchstartX;
    const deltaY = touchendY - touchstartY;
    
    // Agar gorizontal siljish vertikaldan katta bo'lsa va yetarlicha uzun bo'lsa
    if (Math.abs(deltaX) > Math.abs(deltaY) && Math.abs(deltaX) > 40) {
        if (deltaX < 0) {
            window.nextLightboxImage(); // Chapga surilsa (keyingi rasm)
        } else {
            window.prevLightboxImage(); // O'ngga surilsa (oldingi rasm)
        }
    }
}

const lightboxModalObj = document.getElementById('lightbox-modal');
const lightboxImgObj = document.getElementById('lightbox-img');

function attachTouchEvents(el) {
    if (!el) return;
    el.addEventListener('touchstart', e => {
        touchstartX = e.changedTouches[0].clientX;
        touchstartY = e.changedTouches[0].clientY;
    }, {passive: true});

    el.addEventListener('touchend', e => {
        touchendX = e.changedTouches[0].clientX;
        touchendY = e.changedTouches[0].clientY;
        handleGesture();
    }, {passive: true});
}

attachTouchEvents(lightboxModalObj);
attachTouchEvents(lightboxImgObj);

