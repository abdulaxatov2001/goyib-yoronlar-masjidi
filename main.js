    function updateClock() {
        const now = new Date();
        const timeString = now.toLocaleTimeString('uz-UZ', { hour: '2-digit', minute: '2-digit', second: '2-digit' });

        let currentLang = typeof currentAppLanguage !== 'undefined' ? currentAppLanguage : 'uz_cy';
        let dateString = '';

        if (currentLang === 'uz_lt') {
            dateString = `${uzDays[now.getDay()]}, ${now.getDate()}-${uzMonths[now.getMonth()]} ${now.getFullYear()}-yil`;
        } else if (currentLang === 'uz_cy') {
            dateString = `${uzCyDays[now.getDay()]}, ${now.getDate()}-${uzCyMonths[now.getMonth()]} ${now.getFullYear()}-йил`;
        } else if (currentLang === 'ru') {
            const options = { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' };
            dateString = now.toLocaleDateString('ru-RU', options);
            dateString = dateString.charAt(0).toUpperCase() + dateString.slice(1);
        } else {
            const options = { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' };
            dateString = now.toLocaleDateString('en-US', options);
        }

        if (currentHijriDate) {
            const hMonthIndex = parseInt(currentHijriDate.month) - 1;
            const hMonthName = hijriMonths[currentLang] ? hijriMonths[currentLang][hMonthIndex] : hijriMonths['uz_cy'][hMonthIndex];
            const hYearSuffix = (currentLang === 'uz_lt' || currentLang === 'uz_cy') ? (currentLang === 'uz_lt' ? '-yil' : '-йил') : '';
            const hijriStr = `${currentHijriDate.day}-${hMonthName} ${currentHijriDate.year}${hYearSuffix}`;
            const hijriEl = document.getElementById('hijri-date');
            if (hijriEl) hijriEl.textContent = hijriStr;
        }

        document.getElementById('current-time').textContent = timeString;
        document.getElementById('current-date').textContent = dateString;

        if (currentPrayerTimes) {
            updateCountdown(currentPrayerTimes);
        }
    }

    // --- Taymer mantiqi (Countdown) ---
    function updateCountdown(times) {
        const now = new Date();

        // Hozirgi vaqt millisoniyalarda (bugun)
        const currentMs = now.getHours() * 3600000 + now.getMinutes() * 60000 + now.getSeconds() * 1000;

        const prayerKeys = ["bomdod", "quyosh", "peshin", "asr", "shom", "xufton"];
        let nextPrayerKey = "bomdod";
        let targetMs = 0;
        let isTomorrow = false;

        for (let key of prayerKeys) {
            let [h, m] = times[key].split(':').map(Number);
            let timeMs = h * 3600000 + m * 60000;

            if (timeMs > currentMs) {
                nextPrayerKey = key;
                targetMs = timeMs;
                break;
            }
        }

        // Agar hamma namoz o'tgan bo'lsa, ertangi bomdodni olamiz
        if (targetMs === 0) {
            let [h, m] = times["bomdod"].split(':').map(Number);
            targetMs = h * 3600000 + m * 60000;
            isTomorrow = true;
            nextPrayerKey = "bomdod";
        }

        // Barcha itemlardan active klassni olib tashlash
        document.querySelectorAll('.prayer-item').forEach(item => {
            item.classList.remove('active');
        });

        // Keyingi namozga active klass qoshish
        const activeItem = document.querySelector(`.prayer-item[data-prayer="${nextPrayerKey}"]`);
        if (activeItem) {
            activeItem.classList.add('active');
        }

        // Qolgan vaqtni hisoblash
        let diffMs = targetMs - currentMs;
        if (isTomorrow) {
            diffMs = (24 * 3600000 - currentMs) + targetMs;
        }

        let diffSecs = Math.floor(diffMs / 1000);
        let h = Math.floor(diffSecs / 3600);
        let min = Math.floor((diffSecs % 3600) / 60);
        let s = diffSecs % 60;

        document.getElementById('countdown-timer').textContent =
            `-${h.toString().padStart(2, '0')}:${min.toString().padStart(2, '0')}:${s.toString().padStart(2, '0')}`;
    }

    setInterval(updateClock, 1000);
    updateClock();

    // ============================================================
    //  NAMOZ VAQTLARI: 2 ta manba
    //  1. Firebase → Masjid vaqti (KATTA, asosiy)
    //  2. Aladhan API → Astronomik vaqt (kichik, qo'shimcha)
    // ============================================================

    // Firebase bilan ulanish
    let db = null;
    try {
        if (typeof firebaseConfig !== 'undefined' &&
            firebaseConfig.databaseURL &&
            firebaseConfig.apiKey !== 'SIZNING_API_KALITINGIZ') {
            if (!firebase.apps.length) {
                firebase.initializeApp(firebaseConfig);
            }
            db = firebase.database();
            
            // Firebase ulanib bo'lgandan keyingina tashrifni yozamiz
            logVisit();
        }
    } catch(e) {
        console.warn('Firebase ulanmadi:', e.message);
    }

    // Masjid vaqtlarini ko'rsatish (Firebase dan)
    function showMasjidTimes(times) {
        if (!times) return;
        
        // Quyosh vaqti API dan kelgan bo'lsa, shuni ishlatamiz
        if (window.apiQuyoshTime) {
            times.quyosh = window.apiQuyoshTime;
        } else if (!times.quyosh) {
            times.quyosh = '--:--';
        }

        currentPrayerTimes = times;
        document.getElementById('time-bomdod').textContent = '🤲 ' + (times.bomdod || '--:--');
        document.getElementById('time-quyosh').textContent = times.quyosh;
        document.getElementById('time-peshin').textContent = '🤲 ' + (times.peshin || '--:--');
        document.getElementById('time-asr').textContent   = '🤲 ' + (times.asr   || '--:--');
        document.getElementById('time-shom').textContent  = '🤲 ' + (times.shom  || '--:--');
        document.getElementById('time-xufton').textContent= '🤲 ' + (times.xufton|| '--:--');

        // Yangilanish vaqtini ko'rsatish
        if (times.updated_at) {
            const badge = document.getElementById('last-updated');
            if (badge) {
                let updatedText = times.updated_at;
                if (updatedText.includes('-')) {
                    const parts = updatedText.split(' ');
                    if (parts.length === 2) {
                        const dateParts = parts[0].split('-');
                        if (dateParts.length === 3) {
                            updatedText = `${dateParts[2]}.${dateParts[1]}.${dateParts[0]} ${parts[1]}`;
                        }
                    }
                }
                badge.textContent = updatedText + ' da yangilangan';
            }
        }
        updateCountdown(times);
    }

    // Firebase dan real-time o'qish
    let hasLoadedDynamic = false;
    
    function loadFromFirebase() {
        if (!db) return;
        
        // --- 1. Keshdan o'qish (Tezkor ko'rsatish uchun) ---
        try {
            const cached = localStorage.getItem('cached_prayer_times');
            if (cached) {
                showMasjidTimes(JSON.parse(cached));
            }
        } catch(e) { }

        // --- 2. Tarmoqdan (Firebase) eng so'nggi ma'lumotni o'qish ---
        db.ref('prayer_times').on('value', (snapshot) => {
            const data = snapshot.val();
            if (data) {
                // Keshni yangilash
                try { localStorage.setItem('cached_prayer_times', JSON.stringify(data)); } catch(e) {}
                
                showMasjidTimes(data);
                
                // Namoz vaqtlari yuklangach, qolgan og'ir ma'lumotlarni (jamoa, galereya) yuklash
                if (!hasLoadedDynamic) {
                    hasLoadedDynamic = true;
                    setTimeout(() => {
                        if(typeof loadDynamicContent === 'function') loadDynamicContent();
                    }, 500);
                }
            }
        }, (err) => {
            console.warn('Firebase o\'qib bo\'lmadi:', err.message);
        });
    }

    // Aladhan API — astronomik vaqtlar (faqat ko'rsatish uchun)
    async function loadApiTimes() {
        try {
            // Bugungi sanani DD-MM-YYYY formatida olish
            const d = new Date();
            const dd = String(d.getDate()).padStart(2, '0');
            const mm = String(d.getMonth() + 1).padStart(2, '0');
            const yyyy = d.getFullYear();
            const dateStr = `${dd}-${mm}-${yyyy}`;

            // Pop tumani koordinatalari (lat=40.8732, lng=70.9575) va Hanafi mazhabi (school=1)
            // Redirect muammosini oldini olish uchun sanani to'g'ridan-to'g'ri beramiz
            const res = await fetch(`https://api.aladhan.com/v1/timings/${dateStr}?latitude=40.8732&longitude=70.9575&method=3&school=1`);
            const data = await res.json();
            if (data && data.code === 200) {
                const t = data.data.timings;
                const hDate = data.data.date.hijri;
                currentHijriDate = {
                    day: hDate.day,
                    month: hDate.month.number,
                    year: hDate.year
                };
                updateClock(); // Refresh the date string to include hijri
                
                const bomdod = t.Fajr || '--:--';
                const quyosh = t.Sunrise || '--:--';
                const peshin = t.Dhuhr || '--:--';
                const asr = t.Asr || '--:--';
                const shom = t.Maghrib || '--:--';
                const xufton = t.Isha || '--:--';

                document.getElementById('api-bomdod').textContent = '⌚ ' + bomdod;
                document.getElementById('api-quyosh').textContent = quyosh;
                document.getElementById('api-peshin').textContent = '⌚ ' + peshin;
                document.getElementById('api-asr').textContent    = '⌚ ' + asr;
                document.getElementById('api-shom').textContent   = '⌚ ' + shom;
                document.getElementById('api-xufton').textContent = '⌚ ' + xufton;

                // Quyosh masjid vaqtini API'dan olamiz
                window.apiQuyoshTime = quyosh;
                document.getElementById('time-quyosh').textContent = quyosh;
                if (currentPrayerTimes) {
                    currentPrayerTimes.quyosh = quyosh;
                    updateCountdown(currentPrayerTimes);
                }

                // Agar Firebase sozlanmagan bo'lsa, API vaqtlarini asosiy qilib ko'rsat
                if (!db) {
                    const apiTimes = {
                        bomdod, quyosh, peshin, asr, shom, xufton
                    };
                    showMasjidTimes(apiTimes);
                    const badge = document.getElementById('last-updated');
                    if (badge) badge.textContent = '';
                }
            }
        } catch(e) {
            console.warn('API vaqtlarini olib bo\'lmadi:', e.message);
        }
    }

    // Boshlang'ich til va vaqtni yuklash
    setLanguage('uz_cy');
    loadFromFirebase();
    loadApiTimes();

